#!/usr/bin/env python3
"""Generate wiki/reference/floorplan-feasibility.md — read-only feasibility for
STATUS item 5: can the ACTUAL design (two SRAM macros + logic) fit the
competition die, and what would a real floorplan run have to prove?

READS ONLY. It parses the PDK SRAM LEFs (via `sram_budget.parse_lefs`),
`flow/pe_soc.json` (die, macro placements, PDN config) and the measured mapped
area cache `wiki/reference/.floorplan-areas` (refreshed by
`regress/synth_area.sh`). It runs no LibreLane/OpenROAD, no DRC and no LVS.

    python3 tools/gen/floorplan_feasibility.py            # write the page
    python3 tools/gen/floorplan_feasibility.py --check     # exit 1 if stale
    python3 tools/gen/floorplan_feasibility.py --tiles 8x4 # upside allocation
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sram_budget  # noqa: E402  (LEF parsing + the two tile-size constants)

REPO = Path(__file__).resolve().parent.parent.parent
OUT = REPO / "wiki" / "reference" / "floorplan-feasibility.md"
FLOW = REPO / "flow" / "pe_soc.json"
AREAS = REPO / "wiki" / "reference" / ".floorplan-areas"

TILE_TEMPLATE = sram_budget.TILE_TEMPLATE      # 167 x 108
TILE_BLOG = sram_budget.TILE_BLOG              # 200 x 150
# stdcell -> die inflation measured on the routed SERDES run (die / stdcell).
INFLATE = sram_budget.SERDES_DIE_UM2 / sram_budget.SERDES_STDCELL_UM2
GAP_UM = 10.0


def load_flow() -> dict:
    return json.loads(FLOW.read_text())


def load_areas() -> dict[str, dict]:
    out = {}
    for line in AREAS.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split()
        if len(parts) >= 3:
            out[parts[0]] = {"cells": int(parts[1]), "area": float(parts[2])}
    return out


def lef_by_name(macros: list[dict]) -> dict[str, dict]:
    return {m["name"]: m for m in macros}


def placements(cfg: dict, lef: dict[str, dict]):
    """[(instance_path, macro, x, y, orientation)] from the flow config."""
    out = []
    for mtype, spec in cfg.get("MACROS", {}).items():
        macro = lef.get(mtype)
        if macro is None:  # try the display form (prefix stripped)
            for name, m in lef.items():
                if name.replace("RM_IHPSG13_", "") == mtype:
                    macro = m
                    break
        for path, ispec in spec.get("instances", {}).items():
            loc = ispec.get("location", [0, 0])
            out.append((path, macro, float(loc[0]), float(loc[1]),
                        ispec.get("orientation", "?")))
    return out


def bbox(plc) -> tuple[float, float, float, float] | None:
    boxes = []
    for _, macro, x, y, _ in plc:
        if macro is None:
            return None
        boxes.append((x, y, x + macro["w"], y + macro["h"]))
    if not boxes:
        return None
    return (min(b[0] for b in boxes), min(b[1] for b in boxes),
            max(b[2] for b in boxes), max(b[3] for b in boxes))


def overlaps(plc) -> list[str]:
    out = []
    for i in range(len(plc)):
        for j in range(i + 1, len(plc)):
            _, mi, x1, y1, _ = plc[i]
            _, mj, x2, y2, _ = plc[j]
            if mi is None or mj is None:
                continue
            ok = (x2 >= x1 + mi["w"] + GAP_UM or x1 >= x2 + mj["w"] + GAP_UM
                  or y2 >= y1 + mi["h"] + GAP_UM or y1 >= y2 + mj["h"] + GAP_UM)
            if not ok:
                out.append(f"{plc[i][0]} and {plc[j][0]}")
    return out


def build(scenarios) -> str:
    cfg = load_flow()
    areas = load_areas()
    lef = lef_by_name(sram_budget.parse_lefs())
    plc = placements(cfg, lef)
    bb = bbox(plc)
    macro_area = sum(m["area"] for _, m, _, _, _ in plc if m)
    die_cfg = cfg.get("DIE_AREA")
    logic_top = areas.get("tt_um_top")
    logic_soc = areas.get("pe_soc")

    lines: list[str] = []
    add = lines.append

    add("---")
    add("title: Floorplan feasibility — two macros and logic on the real die")
    add("created: 2026-09-23")
    add("updated: 2026-09-23")
    add("type: reference")
    add("tags: [area-budget, floorplan, verification, planning]")
    add("sources: [flow/pe_soc.json, pdk/IHP-Open-PDK/ihp-sg13g2/libs.ref/sg13g2_sram, "
        "wiki/reference/.floorplan-areas, regress/synth_area.sh]")
    add("confidence: medium")
    add("---")
    add("")
    add("# Floorplan feasibility — two macros and logic on the real die")
    add("")
    add("> **Read-only planning (STATUS item 5).** Generated by")
    add("> `tools/gen/floorplan_feasibility.py` from the PDK LEFs,")
    add("> `flow/pe_soc.json` and the measured `synth_area` cache. It runs")
    add("> **no LibreLane/OpenROAD, no DRC and no LVS**. Every number is")
    add("> arithmetic on those sources; the *evidence needed later* section lists")
    add("> what only a real run can prove.")
    add("")

    # ---- what has to be placed -------------------------------------------
    add("## The design to place")
    add("")
    if bb is not None:
        add("| instance | macro | W×H (µm) | at (µm) | orient |")
        add("|---|---|---|---|---|")
        for path, m, x, y, o in plc:
            short = m["name"].replace("RM_IHPSG13_", "") if m else "**LEF missing**"
            add(f"| `{path}` | `{short}` | "
                f"{(m['w'] if m else 0):.0f}×{(m['h'] if m else 0):.0f} | "
                f"({x:g}, {y:g}) | {o} |")
        add("")
        add(f"- **Macro area, both instances:** {macro_area:,.0f} µm² "
            f"(one macro is {macro_area/2:,.0f} µm²).")
        add(f"- **Macro bounding box:** "
            f"{bb[2]-bb[0]:.1f} × {bb[3]-bb[1]:.1f} µm.")
    if logic_top:
        add(f"- **Logic, mapped (`tt_um_top`):** {logic_top['area']:,.0f} µm² "
            f"in {logic_top['cells']:,} standard cells."
            + (f" (`pe_soc` alone: {logic_soc['area']:,.0f} µm², "
               f"{logic_soc['cells']:,} cells.)" if logic_soc else ""))
        add(f"- **Logic, with routing/clock/fill:** ×{INFLATE:.2f} "
            f"(the SERDES-measured stdcell→die factor) → "
            f"{logic_top['area']*INFLATE:,.0f} µm². That factor comes from a")
        add("  different design; the real SoC run must replace it.")
    add("")

    # ---- fit by scenario --------------------------------------------------
    add("## Fit by die scenario")
    add("")
    add("`macro fit` compares the placed bounding box with the die rectangle;")
    add("`occupancy` is (macros + inflated logic) / die area. Occupancy below")
    add("100% is necessary, not sufficient: routing, the pad ring and the PDN")
    add("are separate checks.")
    add("")
    add("| die scenario | die (µm) | area (µm²) | macro bbox fits | macros + inflated logic | occupancy |")
    add("|---|---|---|---|---|---|")
    for label, tw, th, tile in scenarios:
        dw, dh = tw * tile[0], th * tile[1]
        area = dw * dh
        fit = (bb is not None and bb[2] <= dw and bb[3] <= dh)
        total = macro_area + (logic_top["area"] * INFLATE if logic_top else 0)
        occ = total / area * 100
        add(f"| {label} | {dw:.0f} × {dh:.0f} | {area:,.0f} | "
            f"{'yes' if fit else '**no**'} | {total:,.0f} | {occ:.1f}% |")
    add("")

    # ---- what the flow config says ---------------------------------------
    add("## What the flow config declares")
    add("")
    add(f"- `flow/pe_soc.json` declares `DIE_AREA`: "
        f"{die_cfg[2]:g} × {die_cfg[3]:g} µm = the template 6×4 die.")
    add(f"- The two macro placements are declared at " +
        ", ".join(f"`{path}` ({x:g}, {y:g})" for path, _, x, y, _ in plc) +
        ", both `N`.")
    over = overlaps(plc)
    add(f"- The 10 µm placement gap and the die-bound check are enforced on")
    add(f"  every regression by `tools/checks/macro_flow_config.py` (E2): "
        f"{'clean' if not over else 'OVERLAP: ' + ', '.join(over)}.")
    add(f"- `PDN_CFG` is `{cfg.get('PDN_CFG', '**missing**')}`. Its script")
    add("  requests Metal4 macro stripes and ordered connects up to the grid;")
    add("  the E2 static check validates these clauses, not physical connectivity.")
    add("")
    add("**The critical caveat: this is a PADLESS CORE flow.** `pe_soc`'s ports")
    add("are pins at the die boundary; there is no `CORE_AREA`, no pad ring and")
    add("no wrapper in the run. The Tiny Tapeout deliverable")
    add("(`tt_um_protocol_emulator`) does have pads, and the shuttle's pad ring")
    add("occupies the perimeter of the same 1002×432 outline, so its usable core")
    add("is smaller. The placement coordinates above are statically checked to")
    add("fit the configured `DIE_AREA`, not a padded core. Macro `y=10` in particular")
    add("may sit under the ring. That is the first thing a real TT-top floorplan")
    add("must settle.")
    add("")

    # ---- assumptions that differ -----------------------------------------
    add("## Assumptions that differ between the blog and the TT template")
    add("")
    add("| assumption | Jane Street blog | TT template / this repo |")
    add("|---|---|---|")
    add("| tile size | ~200 × 150 µm | **167 × 108 µm** (`ttihp-verilog-template`) |")
    add(f"| per-tile area | 30,000 µm² | {TILE_TEMPLATE[0]*TILE_TEMPLATE[1]:,.0f} µm² |")
    add("| 6×4 die | 1200 × 600 µm (0.720 mm²) | **1002 × 432 µm (0.433 mm²)** |")
    add("| logic per tile | \"~1K cells per tile\" (~24,000 cells) | the template die's own fit is ~8,000 cells |")
    add("| SRAM macro choice | not specified | 30 fixed PDK shapes; the die shape excludes the densest classes |")
    add("")
    add("The two tile figures disagree by +66% in area, and the blog's logic")
    add("figure is inconsistent with the template's own area budget — but")
    add(f"**neither figure threatens this design**: it maps to {logic_top['cells']:,}")
    add("standard cells, well under both. What the tile size *does* decide is")
    add("the macro rectangle, and the template figure is the conservative case.")
    add("")
    add("- **6×4 is the allocation** the blog commits to (8×4 is upside, +33%")
    add("  width at the same height, so it only helps).")
    add("- **The tile size is still unconfirmed.** Re-run this page with")
    add("  `--tiles` when TT finalises it; the SRAM page carries the same")
    add("  warning.")
    add("")
    add("## Evidence needed later (deferred — not run here)")
    add("")
    add("1. **A TT-top flow config.** Only `flow/pe_soc.json` (padless core) and")
    add("   `flow/pe_serdes.json` exist today; the deliverable's wrapper has no")
    add("   floorplan run at all.")
    add("2. **Placement inside a real `CORE_AREA`** with the pad ring present,")
    add("   re-checking both macro locations and the 10 µm gap.")
    add("3. **PDN connectivity for both macros** in a real run: `PSM-0040 All")
    add("   shapes connected`, no `PDN-0189`/`PSM-0069`, and the Metal4 ladder")
    add("   reaching the frame-buffer macro (E2).")
    add("4. **Global-routing congestion** at the real utilisation")
    add("   (`GRT-0116`/`GRT-0704`), then **detailed-route DRC clear**.")
    add("5. **A utilisation/area report** from the routed run to replace the")
    add("   SERDES-derived stdcell-to-die inflation factor used above.")
    add("6. **Macro-alone DRC provenance** (the vendor macro's own violations)")
    add("   and LVS, at the flow stage before tapeout.")
    add("7. **The tile size confirmed** by TT/submission docs, then this page")
    add("   regenerated.")
    add("8. **The full-chip timing/electrical items** from the reviews (the `run`")
    add("   hold, high-fanout nets, and the macro's out-of-table slew/cap).")
    add("")
    add("## Non-actions")
    add("")
    add("No LibreLane, OpenROAD, Magic, KLayout, DRC or LVS was launched to")
    add("produce this page. It is arithmetic over the LEF, the flow config and a")
    add("measured synthesis cache; it is a plan, not a signoff.")
    add("")
    add("## Related")
    add("")
    add("- [[reference/sram-budget]] — the generic macro-vs-die analysis.")
    add("- [[reference/block-diagram]] — what is in the chip.")
    add("- [[STATUS]] — item 5 and the tile-size risk.")
    add("- `flow/pe_soc.json`, `tools/checks/macro_flow_config.py`.")
    add("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tiles", default="6x4",
                    help="tile allocation WxH for the headline scenarios (default 6x4)")
    args = ap.parse_args()

    tw, th = (int(v) for v in args.tiles.lower().split("x"))
    scenarios = [
        (f"Template {tw}×{th}", tw, th, TILE_TEMPLATE),
        (f"Blog-tile {tw}×{th}", tw, th, TILE_BLOG),
        ("Template 8×4 (upside)", 8, 4, TILE_TEMPLATE),
    ]

    rendered = build(scenarios)
    if args.check:
        if not OUT.exists():
            print(f"gen_floorplan_feasibility: {OUT} is missing", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print("gen_floorplan_feasibility: the page is STALE — re-run without --check",
                  file=sys.stderr)
            return 1
        print("floorplan feasibility up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
