module codec_model;
  logic clk=0, rst_n=0, bit_en=0, clr=0;
  always #5 clk=~clk;
  logic [7:0] cfg=0;
  logic tx_bit=0, tx_wire, tx_stuffed;
  logic rx_wire=1, rx_bit, rx_bit_valid, rx_err;
  integer errors=0, cases=0, cells=0;
  pe_codec_mux dut (
    .clk(clk), .rst_n(rst_n), .cfg(cfg), .bit_en(bit_en), .clr(clr),
    .tx_bit(tx_bit), .tx_wire(tx_wire), .tx_stuffed(tx_stuffed),
    .rx_wire(rx_wire), .rx_first(1'b0), .rx_second(1'b0),
    .rx_bit(rx_bit), .rx_bit_valid(rx_bit_valid), .rx_err(rx_err)
  );
  task automatic check(input bit condition, input string message);
    if (!condition) begin
      errors++;
      if (errors<10) $display("FAIL case=%0d %s", cases, message);
    end
  endtask
  task automatic run_stream(input bit usb, input integer count,
                            input logic [255:0] bits,
                            input logic [255:0] flags);
    bit level;
    cfg = usb ? 8'hE3 : 8'h01;
    @(negedge clk); bit_en=0; clr=1;
    @(negedge clk); clr=0;
    level=1;
    for (integer k=0; k<count; k++) begin
      @(negedge clk);
      if (usb) begin
        if (!bits[k]) level=~level;
      end else level=bits[k];
      tx_bit=flags[k] ? 1'bx : bits[k];
      rx_wire=level;
      bit_en=1;
      #1;
      check(tx_stuffed === flags[k], $sformatf("TX stuffing cell %0d", k));
      if (!usb) check(tx_wire === level, $sformatf("CAN TX wire cell %0d", k));
      check(rx_bit_valid === !flags[k], $sformatf("RX validity cell %0d", k));
      check(rx_bit === bits[k], $sformatf("RX raw cell %0d", k));
      @(posedge clk); #1;
      if (usb) check(tx_wire === level, $sformatf("USB NRZI TX wire cell %0d", k));
      check(rx_err === 1'b0, $sformatf("RX error cell %0d", k));
      @(negedge clk); bit_en=0;
      cells++;
    end
    cases++;
  endtask
